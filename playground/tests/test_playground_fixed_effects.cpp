// ---------------------------------------------------------------------------
// Fixture
// ---------------------------------------------------------------------------
// Forty observations on an intercept plus two covariates. The size is set by the
// inference chain rather than by the likelihood: NewtonSchulzInverse needs an
// O(1)-scaled, well-conditioned operand, and X'WX/n only becomes that once there
// are enough rows for the averages to settle. Forty is comfortably past that and
// still runs in seconds.
//
// The covariates are generated by a closed-form rule rather than an RNG so that
// the fixture is identical on every party and in every run -- a seeded RNG would
// also be reproducible, but this way the reference needs no RNG at all.
//
// SCALING IS A PRECONDITION. `plain-lr.cpp` says it plainly: fixed point at
// `precision` 16 has limited headroom and the information matrix must be
// O(1)-scaled. The covariates below are on a standardized scale for that reason,
// not for tidiness.

constexpr std::size_t kNumObs = 40;
constexpr std::size_t kNumFixed = 3;  // intercept + 2 covariates
constexpr std::size_t kNumPoints = 2;

// The last two rows are PADDING (mask 0) and carry deliberately large values, so
// that a mask applied in the wrong place corrupts the aggregates visibly rather
// than subtly.
constexpr std::size_t kNumPadded = 2;

std::vector<double> MakeDesign() {
    std::vector<double> design(kNumObs * kNumFixed, 0.0);
    for (std::size_t i = 0; i < kNumObs; ++i) {
        const bool padded = i >= kNumObs - kNumPadded;
        design[i * kNumFixed + 0] = 1.0;
        if (padded) {
            design[i * kNumFixed + 1] = 7.0;
            design[i * kNumFixed + 2] = -8.0;
            continue;
        }
        design[i * kNumFixed + 1] = 0.5 * (static_cast<double>(i % 5) - 2.0);
        design[i * kNumFixed + 2] = 0.3 * (static_cast<double>(i % 7) - 3.0);
    }
    return design;
}

std::vector<double> MakeOutcome() {
    std::vector<double> outcome(kNumObs, 0.0);
    for (std::size_t i = 0; i < kNumObs; ++i) {
        outcome[i] = ((i * 7) % 11) < 5 ? 1.0 : 0.0;
    }
    return outcome;
}

std::vector<double> MakeMask() {
    std::vector<double> mask(kNumObs, 1.0);
    for (std::size_t i = kNumObs - kNumPadded; i < kNumObs; ++i) {
        mask[i] = 0.0;
    }
    return mask;
}

// Where the operators are evaluated. Modest, so that the linear predictors stay
// well inside the Exp clamp and the weights p(1-p) stay away from zero -- both
// conditions the inference layer needs and neither of which it checks.
const std::vector<double> kBeta = {0.20, 0.50, -0.30};
const std::vector<double> kSecondBeta = {-0.10, 0.25, 0.40};

constexpr double kZCritical = 1.96;

// ---------------------------------------------------------------------------
// Tolerances
// ---------------------------------------------------------------------------
//
// CALIBRATION. Each bound below was first derived a priori (from the 1.526e-5
// fixed-point resolution, from a figure measured by
// `playground/secure-logistic-regression.cpp` and recorded in semantic task
// 0019, or from an error-composition argument), then TIGHTENED once against the
// measured worst error, which is quoted beside it. The ratio is kept at roughly
// 5x to 15x: close enough that a real regression trips it, loose enough to
// survive a different build configuration.
//
// The measurements come from the 3PC build (PROTOCOL=3, DEFAULT_BITWIDTH=32,
// TRIPLES=DUMMY, DIVISION_CORRECTION=ON) on 2026-09-20, and were bit-identical
// across four consecutive runs -- the truncation error in this configuration is
// deterministic, not sampled. That determinism is a property of THIS build and
// must not be assumed for TRIPLES=REAL or another protocol; the margins below
// exist partly to absorb that.
//
// No bound was ever widened to make a failing check pass.

constexpr double kExactish = 4.0 * kResolution;  // ~6.1e-5

// The negative log-likelihood sums 38 unmasked terms, each a LogOnePlusExp
// (measured ~1.8e-4) plus a product. 38 * 2e-4 ~ 8e-3 if the errors aligned;
// they are not systematically signed, so this is a conservative bound.
constexpr double kNegLogLikTolerance = 1.5e-2;  // absolute; measured worst 4.90e-03 -- left as derived

// The ridge penalty is two multiplies and a sum.
constexpr double kPenaltyTolerance = 1.0e-4;  // absolute; measured worst 9.00e-06

// The analytic gradient: one Sigmoid over n elements, then a matmul contracting
// over n = 40. The contraction is where the error accumulates.
constexpr double kGradientTolerance = 3.0e-3;  // absolute; measured worst 6.25e-04

// X'WX/n. Same contraction, with the weights costing one more Sigmoid and two
// multiplies per row.
constexpr double kInformationTolerance = 2.0e-4;  // absolute; measured worst 1.95e-05

// The covariance inverts a matrix whose entries are O(0.2) and whose inverse is
// therefore O(5), so the inverse's absolute error is the operator's noise floor
// amplified by the scale of the answer. Relative is the only sensible mode here.
constexpr double kCovarianceTolerance = 1.0e-3;  // relative; measured worst 3.53e-05

// Standard errors take a square root, which halves relative error, but add
// SecureSqrt's own composed Exp-of-Log error (~4.7e-4 relative, measured).
constexpr double kStandardErrorTolerance = 1.0e-3;  // relative; measured worst 9.33e-05

// The Wald statistic is one division of two quantities each carrying the above.
constexpr double kWaldTolerance = 5.0e-4;  // relative; measured worst 1.03e-05

// Odds ratios exponentiate beta +- 1.96 se, so the standard error's relative
// error is multiplied by roughly 1.96 * se before the exponential.
constexpr double kOddsRatioTolerance = 3.0e-3;  // relative; measured worst 3.22e-04

// ---------------------------------------------------------------------------
// Plaintext mirror
// ---------------------------------------------------------------------------

std::vector<double> PlainLinearPredictor(const std::vector<double>& design,
                                         const std::vector<double>& beta) {
    std::vector<double> eta(kNumObs, 0.0);
    for (std::size_t i = 0; i < kNumObs; ++i) {
        double total = 0.0;
        for (std::size_t j = 0; j < kNumFixed; ++j) {
            total += design[i * kNumFixed + j] * beta[j];
        }
        eta[i] = total;
    }
    return eta;
}

double PlainNegLogLik(const std::vector<double>& design, const std::vector<double>& outcome,
                      const std::vector<double>& mask, const std::vector<double>& beta) {
    const std::vector<double> eta = PlainLinearPredictor(design, beta);
    double total = 0.0;
    for (std::size_t i = 0; i < kNumObs; ++i) {
        total += mask[i] * (RefLogOnePlusExp(eta[i]) - outcome[i] * eta[i]);
    }
    return total;
}

// lambda * sum_{j >= 1} beta_j^2, intercept excluded.
double PlainL2Penalty(const std::vector<double>& beta, double lambda) {
    double total = 0.0;
    for (std::size_t j = 1; j < kNumFixed; ++j) {
        total += beta[j] * beta[j];
    }
    return lambda * total;
}

std::vector<double> PlainGradient(const std::vector<double>& design,
                                 const std::vector<double>& outcome,
                                 const std::vector<double>& mask,
                                 const std::vector<double>& beta, double lambda) {
    const std::vector<double> eta = PlainLinearPredictor(design, beta);
    std::vector<double> gradient(kNumFixed, 0.0);
    for (std::size_t i = 0; i < kNumObs; ++i) {
        const double residual = mask[i] * (RefSigmoid(eta[i]) - outcome[i]);
        for (std::size_t j = 0; j < kNumFixed; ++j) {
            gradient[j] += design[i * kNumFixed + j] * residual;
        }
    }
    for (std::size_t j = 1; j < kNumFixed; ++j) {
        gradient[j] += 2.0 * lambda * beta[j];
    }
    return gradient;
}

// X' W X / n, with W = diag(mask_i * p_i (1 - p_i)).
//
// NOTE the divisor: the operator divides by `rows`, the PADDED width, not by the
// number of real observations. That is the operator's behaviour and the mirror
// reproduces it rather than "correcting" it -- a reference that silently used
// the real count would make a correct operator look wrong.
std::vector<double> PlainInformationOverN(const std::vector<double>& design,
                                          const std::vector<double>& mask,
                                          const std::vector<double>& beta) {
    const std::vector<double> eta = PlainLinearPredictor(design, beta);
    std::vector<double> information(kNumFixed * kNumFixed, 0.0);
    for (std::size_t i = 0; i < kNumObs; ++i) {
        const double probability = RefSigmoid(eta[i]);
        const double weight = mask[i] * probability * (1.0 - probability);
        for (std::size_t j = 0; j < kNumFixed; ++j) {
            for (std::size_t k = 0; k < kNumFixed; ++k) {
                information[j * kNumFixed + k] +=
                    design[i * kNumFixed + j] * weight * design[i * kNumFixed + k];
            }
        }
    }
    // Mirror the operator's rounded reciprocal exactly.
    const double inverse_n = RoundTrip(1.0 / static_cast<double>(kNumObs));
    for (double& entry : information) {
        entry *= inverse_n;
    }
    return information;
}

// ---------------------------------------------------------------------------
// Shared fixture
// ---------------------------------------------------------------------------

struct Fixture {
    logistic::Dataset data;
    std::vector<double> design;
    std::vector<double> outcome;
    std::vector<double> mask;
    std::vector<double> beta;
};

Fixture MakeFixture(EngineRef engine) {
    const std::vector<double> design = MakeDesign();
    const std::vector<double> outcome = MakeOutcome();
    const std::vector<double> mask = MakeMask();

    return Fixture{logistic::Dataset(ShareVector(design, engine), ShareVector(outcome, engine),
                                     ShareVector(mask, engine), kNumObs, kNumFixed),
                   RoundTrip(design), RoundTrip(outcome), RoundTrip(mask), RoundTrip(kBeta)};
}

// ---------------------------------------------------------------------------
// Dataset, including the cached transpose
// ---------------------------------------------------------------------------
void TestDataset(EngineRef engine) {
    Section("logistic::Dataset", engine);

    Fixture fixture = MakeFixture(engine);

    assert(fixture.data.num_obs() == kNumObs);
    assert(fixture.data.num_fixed() == kNumFixed);

    // The cached X^T is the operator's own claim: a p x n row-major buffer that
    // is simultaneously usable as a column-wise n x p view of X. Checking it
    // against an explicit transpose is what makes the claim falsifiable.
    CheckClose("Dataset caches X^T", OpenVector(fixture.data.xt_data),
               RefTranspose(fixture.design, kNumObs, kNumFixed), kExactish, engine);
}

// ---------------------------------------------------------------------------
// ClampNewtonStep
// ---------------------------------------------------------------------------
void TestClampNewtonStep(EngineRef engine) {
    Section("ClampNewtonStep", engine);

    const double bound = static_cast<double>(kMaxNewtonStep);
    const std::vector<double> inputs = {-9.0, -4.0, -3.9, -0.5, 0.0, 0.5, 3.9, 4.0, 12.5};

    std::vector<double> expected;
    expected.reserve(inputs.size());
    for (const double value : inputs) {
        expected.push_back(std::max(-bound, std::min(bound, RoundTrip(value))));
    }

    AV shared = ShareVector(inputs, engine);
    CheckClose("ClampNewtonStep", OpenVector(ClampNewtonStep(shared)), expected, kExactish,
               engine, ErrorMode::Absolute, inputs);
}

// ---------------------------------------------------------------------------
// The objective
// ---------------------------------------------------------------------------
void TestNegLogLik(EngineRef engine) {
    Section("NegLogLikBatched / L2Penalty / PenalizedNegLogLikBatched", engine);

    Fixture fixture = MakeFixture(engine);

    // Two parameter points at once, which is how the line search calls it.
    std::vector<double> packed(kBeta);
    packed.insert(packed.end(), kSecondBeta.begin(), kSecondBeta.end());
    const std::vector<double> packed_rounded = RoundTrip(packed);

    const std::vector<double> first(packed_rounded.begin(), packed_rounded.begin() + kNumFixed);
    const std::vector<double> second(packed_rounded.begin() + kNumFixed, packed_rounded.end());

    const std::vector<double> expected = {
        PlainNegLogLik(fixture.design, fixture.outcome, fixture.mask, first),
        PlainNegLogLik(fixture.design, fixture.outcome, fixture.mask, second)};

    AV beta = ShareVector(packed, engine);
    CheckClose("NegLogLikBatched (K = 2)",
               OpenVector(logistic::NegLogLikBatched(fixture.data, beta, kNumPoints)), expected,
               kNegLogLikTolerance, engine);

    // K = 1, the shape the analytic-gradient path and any single evaluation use.
    AV single = ShareVector(first, engine);
    CheckClose("NegLogLikBatched (K = 1)",
               OpenVector(logistic::NegLogLikBatched(fixture.data, single, 1)), {expected[0]},
               kNegLogLikTolerance, engine);

    // ---- L2Penalty ----
    // lambda == 0 must return exact zeros, not something small: the namespace
    // defaults to no penalty precisely so that these estimates match a PROC
    // GLIMMIX fit, and a penalty that leaked in at 1e-9 would still be a penalty.
    AV zero_penalty = logistic::L2Penalty(beta, kNumPoints, kNumFixed, 0);
    const std::vector<double> zero_opened = OpenVector(zero_penalty);
    for (const double value : zero_opened) {
        assert(value == 0.0 && "L2Penalty with lambda == 0 returned a non-zero value");
    }
    Note("L2Penalty(lambda = 0) is exactly zero, as the GLIMMIX-matching default requires",
         engine);

    const double lambda = 0.25;
    const DataType lambda_scaled = static_cast<DataType>(std::llround(lambda * scale));
    const double lambda_rounded = RoundTrip(lambda);

    const std::vector<double> penalty_expected = {PlainL2Penalty(first, lambda_rounded),
                                                  PlainL2Penalty(second, lambda_rounded)};
    CheckClose("L2Penalty (intercept excluded)",
               OpenVector(logistic::L2Penalty(beta, kNumPoints, kNumFixed, lambda_scaled)),
               penalty_expected, kPenaltyTolerance, engine);

    // The intercept exclusion, checked directly: a point whose ONLY non-zero
    // coordinate is the intercept must incur no penalty at all. A penalty that
    // included column 0 would shrink the intercept toward zero, which is a
    // modelling error rather than a numerical one and would never show up as a
    // tolerance failure elsewhere.
    const std::vector<double> intercept_only = {1.5, 0.0, 0.0};
    AV intercept_shared = ShareVector(intercept_only, engine);
    const std::vector<double> intercept_penalty =
        OpenVector(logistic::L2Penalty(intercept_shared, 1, kNumFixed, lambda_scaled));
    assert(intercept_penalty[0] == 0.0 && "L2Penalty penalized the intercept");
    Note("L2Penalty leaves a pure-intercept point unpenalized", engine);

    // ---- PenalizedNegLogLikBatched = NegLogLik + penalty ----
    std::vector<double> penalized_expected(kNumPoints);
    for (std::size_t k = 0; k < kNumPoints; ++k) {
        penalized_expected[k] = expected[k] + penalty_expected[k];
    }
    CheckClose("PenalizedNegLogLikBatched",
               OpenVector(logistic::PenalizedNegLogLikBatched(fixture.data, beta, kNumPoints,
                                                              lambda_scaled)),
               penalized_expected, kNegLogLikTolerance, engine);
}

