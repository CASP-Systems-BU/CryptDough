// Assertion-based tests for cdough::regression::logistic in
// playground/library/regression.h -- the fixed-effects binary logit added by
// semantic task 0019, together with its Wald inference layer.
//
// WHY THIS LAYER IS THE ONE THAT MOST NEEDS A TEST. The inference chain
//
//     X' W X / n  ->  NewtonSchulzInverse  ->  covariance  ->  SecureSqrt
//                 ->  standard errors      ->  Wald z      ->  NormalCdf
//                 ->  p-value
//
// composes six approximate operators, and its output is a p-value -- a number
// someone will read as evidence. Every intermediate is plausible-looking: a
// covariance matrix of the right shape, positive standard errors, z statistics
// of the right order. None of it announces an error. The whole chain is checked
// here against a plaintext reference computed with exact linear algebra.
//
// The design also pins the cached X^T that `Dataset` builds in its constructor.
// That buffer serves BOTH orientations the namespace needs (row-major p x n is
// X^T; column-wise n x p is X itself, per semantic topic 0001 claim C-09), so
// if it were built wrongly, the gradient and the information matrix would both
// be wrong in a correlated way that a self-consistency check could not see.
//
// PRIVACY: a test, not a privacy demonstration. In particular `SeparationFlag`
// is opened here freely; in production it is one deliberate declassification.
//
// Run: mpirun -np 3 ./test_playground_fixed_effects

#include <algorithm>
#include <cmath>
#include <vector>

#include "cdough.h"

#include "../library/regression.h"
#include "test_util.h"

